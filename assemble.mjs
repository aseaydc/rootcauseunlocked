/* Assemble the deployable Root Cause Unlocked site.
   Run from the workspace root:  node RCU-Site/assemble.mjs

   The site's own pages are hand-written and live in this folder. The one thing
   that is COPIED IN is the assessment: the canonical assessment is the workspace
   root index.html (1.5 MB, live, script-maintained), and it is deliberately NOT
   duplicated here by hand. This script copies it to RCU-Site/quiz/index.html so
   the deployed site serves it at /quiz.

   That keeps exactly one canonical copy of the assessment. Never hand-edit
   RCU-Site/quiz/index.html: edit the root index.html and re-run this script. */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SITE = dirname(fileURLToPath(import.meta.url));
const WORKSPACE = join(SITE, '..');

const SOURCE = join(WORKSPACE, 'index.html');
const DEST_DIR = join(SITE, 'quiz');
const DEST = join(DEST_DIR, 'index.html');

const BANNER = '<!-- GENERATED by RCU-Site/assemble.mjs from the workspace root index.html. Do not edit here. -->\n';

try {
  const html = await readFile(SOURCE, 'utf8');
  await mkdir(DEST_DIR, { recursive: true });
  await writeFile(DEST, BANNER + html, 'utf8');
  const kb = Math.round(Buffer.byteLength(html) / 1024);
  console.log(`assembled: quiz/index.html (${kb} KB) from root index.html`);
  console.log('site is ready to deploy. Upload the contents of RCU-Site/ to the host.');
} catch (err) {
  console.error('assemble failed:', err.message);
  process.exitCode = 1;
}
